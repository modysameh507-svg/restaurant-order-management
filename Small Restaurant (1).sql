CREATE OR ALTER TRIGGER dbo.trg_OrderDetails_Total
ON dbo.ORDERDETAILS
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    IF TRIGGER_NESTLEVEL(@@PROCID) > 1 RETURN;

    UPDATE d
    SET UNITPRICE = m.PRICE
    FROM dbo.ORDERDETAILS AS d
    JOIN inserted AS i ON i.ORDERID = d.ORDERID AND i.ITEMID = d.ITEMID
    JOIN dbo.MENUU AS m ON m.ITEMID = d.ITEMID
    WHERE d.UNITPRICE IS NULL;

    UPDATE o
    SET TOTALPRICE = COALESCE((
        SELECT SUM(d.QUANTITY * d.UNITPRICE)
        FROM dbo.ORDERDETAILS AS d WHERE d.ORDERID = o.ORDERID
    ), 0)
    FROM dbo.ORDERRRR AS o
    WHERE o.ORDERID IN (
        SELECT ORDERID FROM inserted
        UNION
        SELECT ORDERID FROM deleted
    );
END;
